// Command schemagen checks the frozen initial MySQL schema against a freshly
// migrated SQLite schema. Run with go generate in internal/repository/mysql.
// Numbered native additions are checked by TestHourlySchemaContractAndFrozenBaseline.
// No SQLite database is created by MySQL startup.
package main

import (
	"context"
	"crypto/sha256"
	"database/sql"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	sqliterepo "github.com/seakee/cpa-manager-plus/apps/manager-server/internal/repository/sqlite"
)

type column struct {
	name, kind  string
	notNull, pk int
	def         sql.NullString
}
type index struct {
	name    string
	unique  int
	origin  string
	partial int
	sql     sql.NullString
}
type foreignKey struct {
	id                         int
	target, onUpdate, onDelete string
	from, to                   []string
}

type table struct {
	name, source string
	columns      []column
	indexes      []index
	foreign      []foreignKey
	references   []string
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	dir, err := os.MkdirTemp("", "cpa-mysql-schema-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	db, err := sqliterepo.Open(filepath.Join(dir, "schema.sqlite"))
	if err != nil {
		return err
	}
	defer db.Close()
	if err := sqliterepo.RunDerivedStartupMaintenance(context.Background(), db); err != nil {
		return err
	}
	rows, err := db.Query(`select name, sql from sqlite_schema where type = 'table' and name not like 'sqlite_%' and name not like 'usage_monitoring_event_search_v1%' order by name`)
	if err != nil {
		return err
	}
	var tables []table
	for rows.Next() {
		var t table
		if err := rows.Scan(&t.name, &t.source); err != nil {
			return err
		}
		tables = append(tables, t)
	}
	if err := rows.Err(); err != nil {
		return err
	}
	rows.Close()
	for i := range tables {
		if err := inspect(db, &tables[i]); err != nil {
			return err
		}
	}
	var output strings.Builder
	output.WriteString("-- Code generated by go generate; DO NOT EDIT.\n-- Native MySQL 8.4 schema, version 1.\n-- Hash keys preserve complete text identities without prefix uniqueness.\n")
	created := map[string]bool{}
	for len(created) < len(tables) {
		progress := false
		for _, t := range tables {
			if created[t.name] {
				continue
			}
			ready := true
			for _, ref := range t.references {
				if ref != t.name && !created[ref] {
					ready = false
				}
			}
			if !ready {
				continue
			}
			ddl, err := createSQL(t, tables)
			if err != nil {
				return err
			}
			output.WriteString("\n-- statement\n" + ddl + ";\n")
			created[t.name], progress = true, true
		}
		if !progress {
			return fmt.Errorf("cyclic schema dependencies")
		}
	}
	output.WriteString("\n-- statement\ncreate or replace view `usage_monitoring_event_search_v1` as select event_id as rowid, search_text from usage_monitoring_event_projection_v1;\n")
	for _, t := range tables {
		seed, err := seedSQL(db, t)
		if err != nil {
			return err
		}
		output.WriteString(seed)
	}
	// v1 is a historical restore/upgrade contract, not a moving snapshot. New
	// physical structures belong in numbered native migrations. Refuse to
	// silently rewrite the base when SQLite's layout changes.
	baseline, err := os.ReadFile("schema.sql")
	if err != nil {
		return err
	}
	if string(baseline) != output.String() {
		return fmt.Errorf("frozen MySQL v1 baseline differs from SQLite generation; add/review a numbered migration instead of rewriting schema.sql")
	}
	return nil
}

func inspect(db *sql.DB, t *table) error {
	rows, err := db.Query("pragma table_info(" + quote(t.name) + ")")
	if err != nil {
		return err
	}
	for rows.Next() {
		var cid int
		var c column
		if err := rows.Scan(&cid, &c.name, &c.kind, &c.notNull, &c.def, &c.pk); err != nil {
			return err
		}
		t.columns = append(t.columns, c)
	}
	if err := rows.Err(); err != nil {
		return err
	}
	rows.Close()
	rows, err = db.Query("pragma index_list(" + quote(t.name) + ")")
	if err != nil {
		return err
	}
	for rows.Next() {
		var seq int
		var idx index
		if err := rows.Scan(&seq, &idx.name, &idx.unique, &idx.origin, &idx.partial); err != nil {
			return err
		}
		t.indexes = append(t.indexes, idx)
	}
	if err := rows.Err(); err != nil {
		return err
	}
	rows.Close()
	for i := range t.indexes {
		idx := &t.indexes[i]
		if err := db.QueryRow("select sql from sqlite_schema where type='index' and name=?", idx.name).Scan(&idx.sql); err != nil {
			return err
		}
		if !idx.sql.Valid {
			indexRows, err := db.Query("pragma index_info(" + quote(idx.name) + ")")
			if err != nil {
				return err
			}
			var cols []string
			for indexRows.Next() {
				var seq, cid int
				var name string
				if err := indexRows.Scan(&seq, &cid, &name); err != nil {
					return err
				}
				cols = append(cols, quote(name))
			}
			if err := indexRows.Err(); err != nil {
				return err
			}
			indexRows.Close()
			idx.sql.String = "create index " + quote(idx.name) + " on " + quote(t.name) + " (" + strings.Join(cols, ", ") + ")"
		}
	}
	sort.Slice(t.indexes, func(i, j int) bool { return t.indexes[i].name < t.indexes[j].name })
	rows, err = db.Query("pragma foreign_key_list(" + quote(t.name) + ")")
	if err != nil {
		return err
	}
	fks := map[int]*foreignKey{}
	for rows.Next() {
		var id, seq int
		var target, from, to, onUpdate, onDelete, match string
		if err := rows.Scan(&id, &seq, &target, &from, &to, &onUpdate, &onDelete, &match); err != nil {
			return err
		}
		fk := fks[id]
		if fk == nil {
			fk = &foreignKey{id: id, target: target, onUpdate: onUpdate, onDelete: onDelete}
			fks[id] = fk
			t.references = append(t.references, target)
		}
		if seq != len(fk.from) {
			return fmt.Errorf("unordered composite foreign key")
		}
		fk.from = append(fk.from, from)
		fk.to = append(fk.to, to)
	}
	ids := make([]int, 0, len(fks))
	for id := range fks {
		ids = append(ids, id)
	}
	sort.Ints(ids)
	for _, id := range ids {
		t.foreign = append(t.foreign, *fks[id])
	}
	if err := rows.Err(); err != nil {
		return err
	}
	return rows.Close()
}

func createSQL(t table, tables []table) (string, error) {
	var defs []string
	var pk []column
	types := map[string]string{}
	for _, c := range t.columns {
		if c.pk > 0 {
			pk = append(pk, c)
		}
		types[c.name] = strings.ToLower(c.kind)
	}
	sort.Slice(pk, func(i, j int) bool { return pk[i].pk < pk[j].pk })
	integerPK := len(pk) == 1 && strings.EqualFold(pk[0].kind, "integer")
	for _, c := range t.columns {
		kind := ""
		switch strings.ToLower(c.kind) {
		case "integer":
			kind = "bigint"
		case "real":
			kind = "double"
		case "text":
			kind = "longtext"
		case "blob":
			kind = "longblob"
		default:
			return "", fmt.Errorf("unsupported type %s.%s: %s", t.name, c.name, c.kind)
		}
		def := quote(c.name) + " " + kind
		if kind == "longtext" && regexp.MustCompile(`(?i)\b`+regexp.QuoteMeta(c.name)+`\s+text\s+collate\s+nocase`).MatchString(t.source) {
			def += " collate utf8mb4_0900_as_ci"
		}
		if c.notNull > 0 || c.pk > 0 {
			def += " not null"
		}
		if integerPK && c.pk > 0 && strings.Contains(strings.ToLower(t.source), "autoincrement") {
			def += " auto_increment"
		}
		if c.def.Valid {
			if kind == "longtext" || kind == "longblob" {
				def += " default (" + c.def.String + ")"
			} else {
				def += " default " + c.def.String
			}
		}
		defs = append(defs, def)
	}
	if integerPK {
		defs = append(defs, "primary key ("+quote(pk[0].name)+")")
	}
	for _, idx := range t.indexes {
		if integerPK && idx.origin == "pk" {
			continue
		}
		start := strings.Index(idx.sql.String, "(")
		end := lastIndexClosing(idx.sql.String, start)
		if start < 0 || end < 0 {
			return "", fmt.Errorf("cannot parse index %s", idx.name)
		}
		cols := splitSQL(idx.sql.String[start+1 : end])
		name := idx.name
		if strings.HasPrefix(name, "sqlite_autoindex_") {
			name = "uq_" + t.name + "_" + shortHash(name)
		}
		if len(name) > 64 {
			name = name[:50] + "_" + shortHash(name)
		}
		if idx.unique > 0 {
			expr := hashExpression(t, cols, nil)
			where := strings.TrimSpace(idx.sql.String[end+1:])
			if where != "" {
				if !strings.HasPrefix(strings.ToLower(where), "where ") {
					return "", fmt.Errorf("unsupported index suffix %s", where)
				}
				expr = "case when " + where[6:] + " then " + expr + " else null end"
			}
			col := "_unique_" + shortHash(idx.name)
			defs = append(defs, quote(col)+" binary(32) generated always as ("+expr+") stored", "unique key "+quote(name)+" ("+quote(col)+")")
			// The hash enforces full-value uniqueness; the ordinary prefix
			// index serves repository predicates on the original columns.
			name = "lookup_" + shortHash(idx.name)
		}
		// InnoDB permits at most 16 parts. SQLite's wider covering indexes
		// retain their filtering/ordering prefix; the row supplies the rest.
		if len(cols) > 16 {
			cols = cols[:16]
		}
		prefix := min(191, 700/max(1, len(cols)))
		var parts []string
		for _, c := range cols {
			expr := strings.TrimSpace(c)
			direction := ""
			for _, dir := range []string{"desc", "asc"} {
				if strings.HasSuffix(strings.ToLower(expr), " "+dir) {
					expr = strings.TrimSpace(expr[:len(expr)-len(dir)])
					direction = " " + dir
				}
			}
			expr = regexp.MustCompile(`(?i)\s+collate\s+nocase`).ReplaceAllString(expr, "")
			col := strings.Trim(expr, "`\"[] ")
			if kind, ok := types[col]; ok {
				part := quote(col)
				if kind == "text" || kind == "blob" {
					part += "(" + strconv.Itoa(prefix) + ")"
				}
				parts = append(parts, part+direction)
			} else {
				parts = append(parts, "(cast("+expr+" as char("+strconv.Itoa(prefix)+")))"+direction)
			}
		}
		defs = append(defs, "key "+quote(name)+" ("+strings.Join(parts, ", ")+")")
	}
	// Checks in the current schema are deliberately simple (singleton ids).
	for _, check := range regexp.MustCompile(`(?i)check\s*\([^()]*\)`).FindAllString(t.source, -1) {
		defs = append(defs, check)
	}
	for _, fk := range t.foreign {
		var parent table
		for _, candidate := range tables {
			if candidate.name == fk.target {
				parent = candidate
				break
			}
		}
		if parent.name == "" {
			return "", fmt.Errorf("missing referenced table %s", fk.target)
		}
		var parentPK []column
		for _, c := range parent.columns {
			if c.pk > 0 {
				parentPK = append(parentPK, c)
			}
		}
		var fromColumn, toColumn string
		if len(fk.to) == 1 && len(parentPK) == 1 && parentPK[0].name == fk.to[0] && strings.EqualFold(parentPK[0].kind, "integer") {
			toColumn = quote(fk.to[0])
			if fk.onDelete == "SET NULL" {
				fromColumn = quote(fk.from[0])
			} else {
				fromColumn = quote(fmt.Sprintf("_foreign_%d", fk.id))
				defs = append(defs, fromColumn+" bigint generated always as ("+quote(fk.from[0])+") stored")
			}
		} else {
			for _, idx := range parent.indexes {
				if idx.unique == 0 {
					continue
				}
				start := strings.Index(idx.sql.String, "(")
				end := lastIndexClosing(idx.sql.String, start)
				cols := splitSQL(idx.sql.String[start+1 : end])
				if len(cols) != len(fk.to) {
					continue
				}
				match := true
				for i, col := range cols {
					if strings.Trim(col, "`\"[] ") != fk.to[i] {
						match = false
					}
				}
				if match {
					toColumn = quote("_unique_" + shortHash(idx.name))
					break
				}
			}
			if toColumn == "" {
				return "", fmt.Errorf("no unique referenced key for %s.%v", parent.name, fk.to)
			}
			fromColumn = quote(fmt.Sprintf("_foreign_%d", fk.id))
			var cols []string
			for _, col := range fk.from {
				cols = append(cols, quote(col))
			}
			defs = append(defs, fromColumn+" binary(32) generated always as ("+hashExpression(parent, cols, fk.to)+") stored")
		}
		defs = append(defs, fmt.Sprintf("foreign key (%s) references %s (%s) on update %s on delete %s", fromColumn, quote(fk.target), toColumn, fk.onUpdate, fk.onDelete))
	}
	return "create table if not exists " + quote(t.name) + " (\n  " + strings.Join(defs, ",\n  ") + "\n) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_0900_bin", nil
}

func hashExpression(t table, columns, sourceColumns []string) string {
	var fragments []string
	for i, c := range columns {
		expr := strings.TrimSpace(c)
		nocase := strings.Contains(strings.ToLower(expr), "collate nocase")
		expr = regexp.MustCompile(`(?i)\s+collate\s+nocase`).ReplaceAllString(expr, "")
		colName := strings.Trim(expr, "`\"[] ")
		if sourceColumns != nil {
			colName = sourceColumns[i]
		}
		if regexp.MustCompile(`(?i)\b` + regexp.QuoteMeta(colName) + `\s+text\s+collate\s+nocase`).MatchString(t.source) {
			nocase = true
		}
		if nocase {
			expr = "lower(" + expr + ")"
		}
		value := "cast(" + expr + " as char character set utf8mb4)"
		fragments = append(fragments, "length("+value+")", "':'", value, "';'")
	}
	return "unhex(sha2(concat(" + strings.Join(fragments, ", ") + "),256))"
}

func seedSQL(db *sql.DB, t table) (string, error) {
	rows, err := db.Query("select * from " + quote(t.name))
	if err != nil {
		return "", err
	}
	defer rows.Close()
	var out strings.Builder
	var names []string
	for _, c := range t.columns {
		names = append(names, quote(c.name))
	}
	for rows.Next() {
		values := make([]any, len(t.columns))
		dest := make([]any, len(values))
		for i := range values {
			dest[i] = &values[i]
		}
		if err := rows.Scan(dest...); err != nil {
			return "", err
		}
		var literals []string
		for i, v := range values {
			if strings.HasSuffix(t.columns[i].name, "_at_ms") && v != nil {
				v = int64(0)
			}
			if t.columns[i].name == "rebuild_revision" && v != nil {
				v = "mysql-schema-1"
			}
			literals = append(literals, literal(v))
		}
		out.WriteString("\n-- statement\ninsert into " + quote(t.name) + " (" + strings.Join(names, ", ") + ") values (" + strings.Join(literals, ", ") + ") on duplicate key update " + names[0] + " = " + names[0] + ";\n")
	}
	return out.String(), rows.Err()
}
func literal(v any) string {
	switch v := v.(type) {
	case nil:
		return "null"
	case []byte:
		return "'" + strings.ReplaceAll(string(v), "'", "''") + "'"
	case string:
		return "'" + strings.ReplaceAll(v, "'", "''") + "'"
	default:
		return fmt.Sprint(v)
	}
}
func quote(s string) string     { return "`" + strings.ReplaceAll(s, "`", "``") + "`" }
func shortHash(s string) string { return fmt.Sprintf("%x", sha256.Sum256([]byte(s)))[:10] }
func lastIndexClosing(s string, start int) int {
	depth := 0
	quote := byte(0)
	for i := start; i < len(s); i++ {
		c := s[i]
		if quote != 0 {
			if c == quote {
				quote = 0
			}
			continue
		}
		if c == '\'' || c == '"' || c == '`' {
			quote = c
			continue
		}
		if c == '(' {
			depth++
		}
		if c == ')' {
			depth--
			if depth == 0 {
				return i
			}
		}
	}
	return -1
}
func splitSQL(s string) []string {
	var parts []string
	start, depth := 0, 0
	quote := byte(0)
	for i := 0; i < len(s); i++ {
		c := s[i]
		if quote != 0 {
			if c == quote {
				quote = 0
			}
			continue
		}
		if c == '\'' || c == '"' || c == '`' {
			quote = c
			continue
		}
		if c == '(' {
			depth++
		}
		if c == ')' {
			depth--
		}
		if c == ',' && depth == 0 {
			parts = append(parts, s[start:i])
			start = i + 1
		}
	}
	return append(parts, s[start:])
}
